// Writes src/react/playerAssets.generated.ts (gitignored): the rrweb-player text for the lazy ESM chunk.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (ext) => readFileSync(join(root, `worker/public/assets/rrweb-player.2.1.7.${ext}`), 'utf8')
const out = `// GENERATED by scripts/gen-player.mjs. Do not edit.
export const PLAYER_JS: string = ${JSON.stringify(read('js'))}
export const PLAYER_CSS: string = ${JSON.stringify(read('css'))}
`
writeFileSync(join(root, 'src/react/playerAssets.generated.ts'), out)
